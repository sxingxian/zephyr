// Exports the brand kit from the design source (design/kit/shared.cjs, the same kit that draws the
// mockup canvases) into this package: colour tokens, icons, logo, mascot poses and sample scenes.
// Run `pnpm brand:export` after changing the kit; the outputs are committed.

import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');
const K = require('../../../design/kit/shared.cjs');

const write = (p, s) => {
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, s);
};
const banner = '// Generated by packages/brand/scripts/export.mjs from design/kit/shared.cjs. Do not edit.\n';
const xml = (svg) => svg.replace(/^<svg /, '<svg xmlns="http://www.w3.org/2000/svg" ');

// ---- tokens.css ----
const vars = (t) =>
  Object.entries(t)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n');
write(
  join(pkg, 'src/tokens.css'),
  `/* Generated by packages/brand/scripts/export.mjs. Do not edit. */
:root {
${vars(K.LIGHT)}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars(K.DARK).replace(/^ {2}/gm, '    ')}
    color-scheme: dark;
  }
}
:root[data-theme='dark'] {
${vars(K.DARK)}
  color-scheme: dark;
}
:root {
${Object.entries(K.M)
  .map(([k, v]) => `  --m-${k}: ${v};`)
  .join('\n')}
  --font: 'Geist Variable', 'Geist', -apple-system, 'SF Pro Text', system-ui, sans-serif;
  --mono: 'Geist Mono Variable', 'Geist Mono', ui-monospace, 'SF Mono', Menlo, monospace;
  --ease-out: cubic-bezier(0.23, 1, 0.32, 1);
  --ease-in-out: cubic-bezier(0.77, 0, 0.175, 1);
}
/* Mascot idle loops (used inside the mascot SVGs) */
@keyframes zFloat { 0%, 100% { transform: translateY(0); } 50% { transform: translateY(-6px); } }
@keyframes zSway { 0%, 100% { transform: rotate(0deg); } 50% { transform: rotate(-6deg); } }
@keyframes zBlow { 0% { opacity: 0; transform: translateX(-10px); } 30% { opacity: 0.9; } 100% { opacity: 0; transform: translateX(26px); } }
@keyframes zZ { 0% { opacity: 0; transform: translate(0, 6px); } 35% { opacity: 1; } 100% { opacity: 0; transform: translate(10px, -22px); } }
@media (prefers-reduced-motion: reduce) {
  svg * { animation: none !important; }
}
`,
);

// ---- icons ----
write(
  join(pkg, 'src/generated/icons.ts'),
  `${banner}export const ICONS = ${JSON.stringify(K.IC, null, 2)} as const;\nexport type IconName = keyof typeof ICONS;\n`,
);

// ---- logo ----
const mark = K.markBreeze('currentColor', 24)
  .replace(/ width="24" height="24"/, '')
  .replace(/ style="[^"]*"/, '');
write(join(pkg, 'assets/logo/mark.svg'), xml(mark.replace(/currentColor/g, '#0D1117')));
write(join(pkg, 'assets/logo/mark-white.svg'), xml(mark.replace(/currentColor/g, '#FFFFFF')));

// ---- mascot poses ----
const POSES = ['breeze', 'peek', 'hold', 'wave', 'nap', 'guard', 'ponder', 'hop', 'face'];
const mascot = {};
for (const p of POSES) {
  const svg = K.mascotPose(p, 220, 250).replace(/ width="220" height="250"/, '');
  mascot[p] = svg;
  write(join(pkg, `assets/mascot/${p}.svg`), xml(svg));
}

// ---- sample scenes (placeholders until real sample shoots are licensed) ----
const KINDS = [
  'dunes',
  'sea',
  'peaks',
  'city',
  'bloom',
  'product',
  'sneaker',
  'interior',
  'forest',
  'food',
  'portrait',
  'couple',
  'dusk',
  'pet',
  'doc',
];
for (const k of KINDS) {
  const svg = K.photo(k, { label: `Sample photo: ${k}` })
    .replace(/ width="100%" height="100%"/, ' width="1200" height="900"')
    .replace(/ style="[^"]*"/, '');
  write(join(pkg, `assets/samples/${k}.svg`), xml(svg));
}

write(
  join(pkg, 'src/generated/brand.ts'),
  `${banner}export const MARK_SVG = ${JSON.stringify(mark)};\nexport const MASCOT = ${JSON.stringify(mascot, null, 2)} as const;\nexport type MascotPose = keyof typeof MASCOT;\nexport const SAMPLE_KINDS = ${JSON.stringify(KINDS)} as const;\nexport type SampleKind = (typeof SAMPLE_KINDS)[number];\nexport const MASCOT_PALETTE = ${JSON.stringify(K.M, null, 2)} as const;\n`,
);
console.log(
  'brand exported:',
  POSES.length,
  'poses,',
  KINDS.length,
  'samples,',
  Object.keys(K.IC).length,
  'icons',
);
